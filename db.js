const db = {
    // Auth logic
    async login(email, password) {
        const { data, error } = await supabaseClient.auth.signInWithPassword({ email, password });
        return { data, error };
    },

    async signup(email, password) {
        const { data, error } = await supabaseClient.auth.signUp({ email, password });
        return { data, error };
    },

    async logout() {
        const { error } = await supabaseClient.auth.signOut();
        return { error };
    },

    async getCurrentUser() {
        if (!supabaseClient) return null;
        try {
            const { data, error } = await supabaseClient.auth.getUser();
            if (error) console.warn("Auth check:", error.message);
            return data?.user || null;
        } catch (e) {
            console.error("Error fetching user:", e);
            return null;
        }
    },

    onAuthStateChange(callback) {
        if (!supabaseClient) return;
        supabaseClient.auth.onAuthStateChange((event, session) => {
            callback(event, session);
        });
    },

    // Data Fetching Logic
    async getStreamingServices() {
        if (!supabaseClient) return [];
        try {
            const { data, error } = await supabaseClient.from('streaming_services').select('*');
            if (error) console.error("Error fetching streaming services:", error);
            return data || [];
        } catch(e) { return []; }
    },

    async getFranchises() {
        if (!supabaseClient) return [];
        try {
            const { data, error } = await supabaseClient.from('franchises').select('*');
            if (error) console.error("Error fetching franchises:", error);
            return data || [];
        } catch(e) { return []; }
    },

    async getContentItems() {
        if (!supabaseClient) return [];
        try {
            const { data, error } = await supabaseClient
                .from('content_items')
                .select(`
                    *,
                    streaming_services ( name, icon_url ),
                    franchises ( name )
                `)
                .order('title', { ascending: true });
            
            if (error) console.error("Error fetching content items:", error);
            return data || [];
        } catch(e) { return []; }
    },

    async getUserWatchlist(userId) {
        if (!userId || !supabaseClient) return [];
        try {
            const { data, error } = await supabaseClient
                .from('user_watchlist')
                .select('*')
                .eq('user_id', userId);
            
            if (error) console.error("Error fetching watchlist:", error);
            return data || [];
        } catch(e) { return []; }
    },

    // Updates
    async upsertWatchlistItem(userId, contentItemId, status) {
        if (!userId) return { error: new Error('User not logged in') };
        
        const { data, error } = await supabaseClient
            .from('user_watchlist')
            .upsert({ 
                user_id: userId, 
                content_item_id: contentItemId, 
                status: status,
                updated_at: new Date().toISOString()
            }, { onConflict: 'user_id,content_item_id' })
            .select();
            
        if (error) console.error("Error upserting watchlist item:", error);
        return { data, error };
    },

    // Admin Tools
    async insertContentItem(itemData) {
        if (!supabaseClient) return { error: new Error('Supabase client not initialized') };
        
        // Ensure the ID is unique or generated by Supabase if omitted.
        // Assuming TMDB ID can be used or we let Supabase create a UUID.
        // If we use TMDB id, we should pass it. Let's pass the payload directly.
        
        const { data, error } = await supabaseClient
            .from('content_items')
            .upsert(itemData, { onConflict: 'id' })
            .select();
            
        if (error) console.error("Error inserting content item:", error);
        return { data, error };
    },

    async getSystemSetting(key) {
        if (!supabaseClient) return null;
        try {
            const { data, error } = await supabaseClient
                .from('system_settings')
                .select('value')
                .eq('id', key)
                .single();
            if (error && error.code !== 'PGRST116') { // PGRST116 is "no rows returned", which is fine for a missing setting
                console.error("Error fetching setting:", error);
            }
            return data?.value || null;
        } catch(e) { return null; }
    },

    async setSystemSetting(key, value) {
        if (!supabaseClient) return { error: new Error('Supabase client not initialized') };
        
        const { data, error } = await supabaseClient
            .from('system_settings')
            .upsert({ 
                id: key, 
                value: value,
                updated_at: new Date().toISOString()
            }, { onConflict: 'id' })
            .select();
            
        if (error) console.error("Error setting system setting:", error);
        return { data, error };
    }
};

window.db = db;
